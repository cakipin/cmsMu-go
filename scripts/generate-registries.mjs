import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT_DIR = path.resolve(__dirname, "..");

const THEMES_DIR = path.join(ROOT_DIR, "apps/cms-api/src/themes");
const THEMES_OUTPUT = path.join(THEMES_DIR, "registry.generated.ts");

const PLUGINS_DIR = path.join(ROOT_DIR, "apps/cms-api/src/plugins");
const PLUGINS_OUTPUT = path.join(PLUGINS_DIR, "registry.generated.ts");

console.log("⚡ [Registry Discovery] Scanning themes and plugins directories...");

/**
 * 1. Scan Themes
 */
function generateThemesRegistry() {
  if (!fs.existsSync(THEMES_DIR)) {
    console.warn(`⚠️ [Themes] Directory ${THEMES_DIR} not found, skipping.`);
    return;
  }

  const entries = fs.readdirSync(THEMES_DIR, { withFileTypes: true });
  const themeDirs = entries
    .filter(e => e.isDirectory() && !e.name.startsWith("."))
    .map(e => e.name)
    .filter(name => fs.existsSync(path.join(THEMES_DIR, name, "index.ts")));

  // Pastikan 'default' selalu berada di urutan pertama
  themeDirs.sort((a, b) => {
    if (a === "default") return -1;
    if (b === "default") return 1;
    return a.localeCompare(b);
  });

  const discoveredThemes = [];

  for (const dir of themeDirs) {
    const manifestPath = path.join(THEMES_DIR, dir, "theme.json");
    let meta = {
      id: dir,
      name: dir.charAt(0).toUpperCase() + dir.slice(1) + " Theme",
      version: "1.0.0",
      author: "CMSMu Community",
      description: `Tema kustom CMSMu: ${dir}`,
    };

    if (fs.existsSync(manifestPath)) {
      try {
        const raw = JSON.parse(fs.readFileSync(manifestPath, "utf-8"));
        meta = { ...meta, ...raw, id: raw.id || dir };
      } catch (err) {
        console.warn(`⚠️ [Themes] Error reading theme.json in ${dir}:`, err.message);
      }
    }

    discoveredThemes.push({
      dir,
      meta,
      varName: "Theme_" + dir.replace(/[^a-zA-Z0-9_]/g, "_"),
    });
  }

  let code = `// ⚠️ AUTO-GENERATED BY scripts/generate-registries.mjs\n`;
  code += `// DILARANG MENGEDIT BERKAS INI SECARA MANUAL.\n\n`;
  code += `import type { ThemeStructure } from "./types";\n`;

  for (const t of discoveredThemes) {
    code += `import ${t.varName} from "./${t.dir}";\n`;
  }

  code += `\nexport interface ThemeMeta {\n`;
  code += `  id: string;\n`;
  code += `  name: string;\n`;
  code += `  version: string;\n`;
  code += `  author: string;\n`;
  code += `  description: string;\n`;
  code += `}\n\n`;

  code += `export const availableThemes: ThemeMeta[] = [\n`;
  for (const t of discoveredThemes) {
    code += `  ${JSON.stringify(t.meta, null, 2).replace(/\n/g, "\n  ")},\n`;
  }
  code += `];\n\n`;

  code += `export const themeRenderers: Record<string, ThemeStructure> = {\n`;
  for (const t of discoveredThemes) {
    code += `  ${JSON.stringify(t.meta.id)}: ${t.varName},\n`;
    if (t.dir !== t.meta.id) {
      code += `  ${JSON.stringify(t.dir)}: ${t.varName},\n`;
    }
  }
  code += `};\n\n`;

  code += `export const getActiveTheme = (id?: string): ThemeStructure => {\n`;
  code += `  if (id && themeRenderers[id]) {\n`;
  code += `    return themeRenderers[id];\n`;
  code += `  }\n`;
  code += `  return themeRenderers["default"] || ${discoveredThemes[0]?.varName || "{}"};\n`;
  code += `};\n`;

  fs.writeFileSync(THEMES_OUTPUT, code, "utf-8");
  console.log(`✅ [Themes] Auto-discovered ${discoveredThemes.length} themes -> ${path.relative(ROOT_DIR, THEMES_OUTPUT)}`);
}

/**
 * 2. Scan Plugins
 */
function generatePluginsRegistry() {
  if (!fs.existsSync(PLUGINS_DIR)) {
    console.warn(`⚠️ [Plugins] Directory ${PLUGINS_DIR} not found, skipping.`);
    return;
  }

  const entries = fs.readdirSync(PLUGINS_DIR, { withFileTypes: true });
  const pluginDirs = entries
    .filter(e => e.isDirectory() && !e.name.startsWith("."))
    .map(e => e.name)
    .filter(name => fs.existsSync(path.join(PLUGINS_DIR, name, "index.ts")));

  pluginDirs.sort();

  const discoveredPlugins = [];

  for (const dir of pluginDirs) {
    const manifestPath = path.join(PLUGINS_DIR, dir, "plugin.json");
    let meta = {
      id: dir,
      name: dir.charAt(0).toUpperCase() + dir.slice(1) + " Plugin",
      version: "1.0.0",
      author: "CMSMu Community",
      description: `Plugin kustom CMSMu: ${dir}`,
    };

    if (fs.existsSync(manifestPath)) {
      try {
        const raw = JSON.parse(fs.readFileSync(manifestPath, "utf-8"));
        meta = { ...meta, ...raw, id: raw.id || dir };
      } catch (err) {
        console.warn(`⚠️ [Plugins] Error reading plugin.json in ${dir}:`, err.message);
      }
    }

    discoveredPlugins.push({
      dir,
      meta,
      varName: "Plugin_" + dir.replace(/[^a-zA-Z0-9_]/g, "_"),
    });
  }

  let code = `// ⚠️ AUTO-GENERATED BY scripts/generate-registries.mjs\n`;
  code += `// DILARANG MENGEDIT BERKAS INI SECARA MANUAL.\n\n`;
  code += `import type { Hono } from "hono";\n`;
  code += `import type { Bindings } from "../types";\n`;

  for (const p of discoveredPlugins) {
    code += `import ${p.varName} from "./${p.dir}";\n`;
  }

  code += `\nexport interface PluginMeta {\n`;
  code += `  id: string;\n`;
  code += `  name: string;\n`;
  code += `  version: string;\n`;
  code += `  author: string;\n`;
  code += `  description: string;\n`;
  code += `  category?: string;\n`;
  code += `}\n\n`;

  code += `export const availablePlugins: PluginMeta[] = [\n`;
  for (const p of discoveredPlugins) {
    code += `  ${JSON.stringify(p.meta, null, 2).replace(/\n/g, "\n  ")},\n`;
  }
  code += `];\n\n`;

  code += `export interface PluginModuleEntry {\n`;
  code += `  id: string;\n`;
  code += `  dir: string;\n`;
  code += `  meta: PluginMeta;\n`;
  code += `  register: (app: Hono<{ Bindings: Bindings }>) => void;\n`;
  code += `}\n\n`;

  code += `export const pluginModules: PluginModuleEntry[] = [\n`;
  for (let i = 0; i < discoveredPlugins.length; i++) {
    const p = discoveredPlugins[i];
    code += `  {\n`;
    code += `    id: ${JSON.stringify(p.meta.id)},\n`;
    code += `    dir: ${JSON.stringify(p.dir)},\n`;
    code += `    meta: availablePlugins[${i}],\n`;
    code += `    register: ${p.varName},\n`;
    code += `  },\n`;
  }
  code += `];\n`;

  fs.writeFileSync(PLUGINS_OUTPUT, code, "utf-8");
  console.log(`✅ [Plugins] Auto-discovered ${discoveredPlugins.length} plugins -> ${path.relative(ROOT_DIR, PLUGINS_OUTPUT)}`);
}

generateThemesRegistry();
generatePluginsRegistry();
console.log("✨ [Registry Discovery] Completed successfully.");
